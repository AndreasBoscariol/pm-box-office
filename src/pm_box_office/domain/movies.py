def upsert_movie_by_source(
    conn: Any,
    *,
    source: str,
    source_movie_id: str,
    title: str,
    movie_url: str | None = None,
    release_year: int | None = None,
    release_date: str | dt.date | None = None,
    opusdata_id: str | None = None,
    match_status: str = "matched",
    match_method: str | None = "source_primary_key",
    match_score: float | None = 1.0,
) -> int:
    """Return the shared movies.movie_id for a source-specific movie identity."""
    ensure_movie_identity_schema(conn)
    movie_id = find_movie_id_by_source(conn, source=source, source_movie_id=source_movie_id)
    if movie_id is None and movie_url is not None:
        row = conn.execute("SELECT movie_id FROM movies WHERE movie_url = %s", (movie_url,)).fetchone()
        movie_id = int(row[0]) if row is not None else None
    if movie_id is None and opusdata_id is not None:
        row = conn.execute("SELECT movie_id FROM movies WHERE opusdata_id = %s", (opusdata_id,)).fetchone()
        movie_id = int(row[0]) if row is not None else None

    if movie_id is None:
        row = conn.execute(
            """
            INSERT INTO movies (movie_url, title, release_year, release_date, opusdata_id, updated_at)
            VALUES (%s, %s, %s, %s, %s, CURRENT_TIMESTAMP)
            RETURNING movie_id
            """,
            (movie_url, title, release_year, release_date, opusdata_id),
        ).fetchone()
        movie_id = int(row[0])
    else:
        conn.execute(
            """
            UPDATE movies
            SET
                movie_url = COALESCE(%s, movie_url),
                title = COALESCE(%s, title),
                release_year = COALESCE(%s, release_year),
                release_date = COALESCE(%s, release_date),
                opusdata_id = COALESCE(%s, opusdata_id),
                updated_at = CURRENT_TIMESTAMP
            WHERE movie_id = %s
            """,
            (movie_url, title, release_year, release_date, opusdata_id, movie_id),
        )

    upsert_movie_source_id(
        conn,
        movie_id=movie_id,
        source=source,
        source_movie_id=source_movie_id,
        source_title=title,
        match_status=match_status,
        match_method=match_method,
        match_score=match_score,
    )
    if opusdata_id:
        upsert_movie_source_id(
            conn,
            movie_id=movie_id,
            source=SOURCE_THE_NUMBERS_OPUSDATA,
            source_movie_id=opusdata_id,
            source_title=title,
            match_status="matched",
            match_method="source_primary_key",
            match_score=1.0,
        )
    return movie_id
