AMC_EVENT_REJECTION_RE = re.compile(
    r"private theatre rental|opening night fan event|telemundo|copa mundial|"
    r"anniversary|studio ghibli fest|bonus footage|q\s*&\s*a|one night only|"
    r"special show|ufc|live in imax",
    re.IGNORECASE,
)
AMC_SENSORY_SUFFIX_RE = re.compile(r"^\s*(?P<title>.+?)\s*:\s*sensory friendly screening\s*$", re.IGNORECASE)


def strip_title_year(value: str) -> str:
    return re.sub(r"\s*\((?:19|20)\d{2}[^)]*\)", "", value).strip()


def strip_title_qualifiers(value: str) -> str:
    text = strip_title_year(value)
    text = re.sub(
        r"\s*\((?:wide|limited|imax|3d|event|fathom event|dir\.[^)]+)[^)]*\)",
        "",
        text,
        flags=re.IGNORECASE,
    )
    return text.strip()


def amc_match_title_key(value: str) -> tuple[str | None, str | None]:
    sensory = AMC_SENSORY_SUFFIX_RE.match(value)
    if sensory:
        return normalize_title(strip_title_qualifiers(sensory.group("title"))), "sensory_friendly_prefix"
    if AMC_EVENT_REJECTION_RE.search(value):
        return None, "event_or_nonstandard_amc_listing"
    return normalize_title(strip_title_qualifiers(value)), None


def parse_title_year(value: str | None) -> int | None:
    if not value:
        return None
    match = re.search(r"\b(19\d{2}|20\d{2})\b", value)
    return int(match.group(1)) if match else None


def parse_the_numbers_url_year(value: str | None) -> int | None:
    if not value:
        return None
    match = re.search(r"\((19\d{2}|20\d{2})(?:-[^)]+)?\)", value)
    return int(match.group(1)) if match else None


def the_numbers_title_keys(title: str, movie_url: str | None) -> set[str]:
    values = {title, strip_title_year(title)}
    if movie_url:
        tail = movie_url.rstrip("/").split("/")[-1]
        tail = re.sub(r"\((?:19|20)\d{2}(?:-[^)]+)?\)$", "", tail).replace("-", " ")
        values.add(tail)
        values.add(strip_title_year(tail))
    return {normalize_title(strip_title_qualifiers(value)) for value in values if value}


def load_the_numbers_match_candidates(conn: Any) -> dict[str, dict[int, tuple[Any, ...]]]:
    if not relation_exists(conn, "movie_source_ids"):
        return {}
    sched_sql = (
        """
            SELECT
                movie_url,
                MIN(release_date) AS schedule_release_date
            FROM the_numbers_release_schedule
            GROUP BY movie_url
        """
        if relation_exists(conn, "the_numbers_release_schedule")
        else """
            SELECT
                NULL::text AS movie_url,
                NULL::date AS schedule_release_date
            WHERE FALSE
        """
    )
    chart_sql = (
        """
            SELECT DISTINCT ON (movie_url)
                movie_url,
                chart_date::date AS latest_chart_date,
                days_in_release,
                gross_usd
            FROM daily_chart_pages
            ORDER BY movie_url, chart_date::date DESC
        """
        if relation_exists(conn, "daily_chart_pages")
        else """
            SELECT
                NULL::text AS movie_url,
                NULL::date AS latest_chart_date,
                NULL::integer AS days_in_release,
                NULL::integer AS gross_usd
            WHERE FALSE
        """
    )
    rows = conn.execute(
        f"""
        WITH sched AS (
            {sched_sql}
        ),
        chart AS (
            {chart_sql}
        ),
        tn AS (
            SELECT DISTINCT ON (msi.movie_id)
                msi.movie_id,
                COALESCE(m.title, msi.source_title) AS title,
                msi.source_movie_id AS movie_url,
                m.release_date,
                m.release_year,
                sched.schedule_release_date,
                chart.latest_chart_date,
                chart.days_in_release,
                chart.gross_usd
            FROM movie_source_ids msi
            JOIN movies m ON m.movie_id = msi.movie_id
            LEFT JOIN sched ON sched.movie_url = msi.source_movie_id
            LEFT JOIN chart ON chart.movie_url = msi.source_movie_id
            WHERE msi.source = 'the_numbers'
            ORDER BY
                msi.movie_id,
                COALESCE(sched.schedule_release_date, chart.latest_chart_date, m.release_date) DESC NULLS LAST
        )
        SELECT * FROM tn
        """
    ).fetchall()
    by_key: dict[str, dict[int, tuple[Any, ...]]] = {}
    for row in rows:
        movie_id = int(row[0])
        for key in the_numbers_title_keys(str(row[1]), row[2]):
            if key:
                by_key.setdefault(key, {})[movie_id] = tuple(row)
    return by_key


def score_amc_the_numbers_candidate(amc_row: tuple[Any, ...], candidate: tuple[Any, ...]) -> tuple[float | None, str]:
    _, amc_title, _, first_exhibition_date, _, _ = amc_row
    _, _, movie_url, movie_release_date, release_year, schedule_release_date, latest_chart_date, _, _ = candidate
    amc_year = parse_title_year(amc_title)
    candidate_year = parse_the_numbers_url_year(movie_url) or release_year
    if amc_year and candidate_year and amc_year != candidate_year:
        return None, "explicit_year_mismatch"
    release_date = schedule_release_date or movie_release_date
    if release_date and first_exhibition_date:
        diff = (first_exhibition_date - release_date).days
        if -14 <= diff <= 35:
            return float(120 - abs(diff)), "release_schedule_window"
        return None, "title_match_but_release_date_outside_window"
    if latest_chart_date and first_exhibition_date:
        diff = abs((first_exhibition_date - latest_chart_date).days)
        if diff <= 14:
            return float(95 - diff), "active_daily_chart_window"
        return None, "title_match_but_latest_chart_date_stale"
    if candidate_year and first_exhibition_date and candidate_year == first_exhibition_date.year and not release_date:
        return 70.0, "url_year_current_no_release_date"
    return None, "title_match_but_no_current_date_evidence"


def choose_amc_the_numbers_match(
    amc_row: tuple[Any, ...],
    candidates_by_key: dict[str, dict[int, tuple[Any, ...]]],
) -> tuple[int | None, str, float | None]:
    _, amc_title, _, _, _, _ = amc_row
    key, rejected_reason = amc_match_title_key(str(amc_title))
    if rejected_reason and key is None:
        return None, rejected_reason, None
    candidates = list(candidates_by_key.get(key or "", {}).values())
    if not candidates:
        return None, "no_normalized_title_candidate_in_the_numbers", None
    scored: list[tuple[float, str, tuple[Any, ...]]] = []
    reject_reasons: list[str] = []
    for candidate in candidates:
        score, method = score_amc_the_numbers_candidate(amc_row, candidate)
        if score is None:
            reject_reasons.append(method)
        else:
            scored.append((score, method, candidate))
    scored.sort(key=lambda item: item[0], reverse=True)
    if scored and (len(scored) == 1 or scored[0][0] - scored[1][0] >= 10):
        score, method, candidate = scored[0]
        if rejected_reason == "sensory_friendly_prefix":
            method = f"{method}_sensory_prefix"
        return int(candidate[0]), method, score / 120.0
    if scored:
        return None, "ambiguous_scored_candidates", None
    for reason in [
        "explicit_year_mismatch",
        "title_match_but_release_date_outside_window",
        "title_match_but_latest_chart_date_stale",
        "title_match_but_no_current_date_evidence",
    ]:
        if reason in reject_reasons:
            return None, reason, None
    return None, reject_reasons[0] if reject_reasons else "rejected_unknown", None


def apply_amc_the_numbers_matches(conn: Any) -> None:
    candidates_by_key = load_the_numbers_match_candidates(conn)
    amc_rows = conn.execute(
        """
        SELECT
            a.amc_movie_id,
            a.amc_movie_name,
            a.movie_id,
            MIN(s.exhibition_date) AS first_exhibition_date,
            MAX(s.exhibition_date) AS last_exhibition_date,
            COUNT(s.showtime_id) AS showtime_count
        FROM amc_movies a
        LEFT JOIN amc_showtimes s ON s.amc_movie_id = a.amc_movie_id
        GROUP BY a.amc_movie_id, a.amc_movie_name, a.movie_id
        """
    ).fetchall()
    for row in amc_rows:
        amc_movie_id, amc_movie_name, _, _, _, _ = row
        movie_id, method, score = choose_amc_the_numbers_match(tuple(row), candidates_by_key)
        status = "matched" if movie_id is not None else "unmatched"
        conn.execute(
            """
            INSERT INTO movie_source_ids (
                movie_id, source, source_movie_id, source_title,
                match_status, match_method, match_score, matched_at
            )
            VALUES (%s, 'amc', %s, %s, %s, %s, %s, CURRENT_TIMESTAMP)
            ON CONFLICT(source, source_movie_id) DO UPDATE SET
                movie_id = excluded.movie_id,
                source_title = excluded.source_title,
                match_status = excluded.match_status,
                match_method = excluded.match_method,
                match_score = excluded.match_score,
                matched_at = excluded.matched_at
            """,
            (movie_id, amc_movie_id, amc_movie_name, status, method, score),
        )


